import path from "node:path";
import { existsSync, readdirSync, readFileSync, realpathSync, statSync } from "node:fs";
import { isDeepStrictEqual } from "node:util";
import { assertPluginManifest, type InstalledPluginManifest } from "./manifest";
import { isOfficialPluginId } from "./official";

export function readInstalledManifest(directory: string): InstalledPluginManifest {
  const manifest: unknown = JSON.parse(readFileSync(path.join(directory, "manifest.json"), "utf8"));
  assertPluginManifest(manifest);
  const base = realpathSync(directory) + path.sep;
  if (!realpathSync(path.join(directory, manifest.entry)).startsWith(base)) throw new Error("插件入口越出安装目录");
  return manifest;
}

/** Read only the package directories generated by the application build. */
export function bundledPluginPackages(root: string) {
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true }).flatMap(entry => {
    if (!entry.isDirectory()) return [];
    try {
      const directory = path.join(root, entry.name);
      const manifest = readInstalledManifest(directory);
      if (!isOfficialPluginId(manifest.id)) return [];
      return [{ directory, manifest, available: () => {
        try {
          const current = readInstalledManifest(directory);
          return isDeepStrictEqual(current, manifest) && statSync(path.join(directory, manifest.entry)).isFile();
        } catch {
          return false;
        }
      } }];
    } catch {
      return [];
    }
  });
}

export function bundledPluginPackageLoader(root: string): () => ReturnType<typeof bundledPluginPackages> {
  let fingerprint: string | undefined;
  let packages: ReturnType<typeof bundledPluginPackages> = [];
  return () => {
    let next = "";
    try {
      next = readdirSync(root, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => entry.name)
        .sort()
        .join("\n");
    } catch {
      next = "";
    }
    if (next !== fingerprint) {
      fingerprint = next;
      packages = bundledPluginPackages(root);
    }
    return packages;
  };
}
